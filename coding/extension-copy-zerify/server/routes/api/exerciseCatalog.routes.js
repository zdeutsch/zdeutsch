const express = require("express");
const asyncHandler = require("../../middleware/asyncHandler");
const service = require("../../services/exerciseCatalogService");
const router = express.Router();
const level = req => String(req.query.level || "b2").toLowerCase();
router.get("/", asyncHandler(async (req, res) => res.json({ ok: true, data: await service.list(level(req)) })));
router.get("/targets", asyncHandler(async (req, res) => res.json({ ok: true, data: await service.targets(level(req)) })));
router.put("/additions/:id", asyncHandler(async (req, res) => res.json({ ok: true, data: await service.updateExercise(req.params.id, req.body, level(req)) })));
router.put("/names/:id", asyncHandler(async (req, res) => res.json({ ok: true, data: await service.saveNames(req.params.id, req.body, level(req)) })));
module.exports = router;
